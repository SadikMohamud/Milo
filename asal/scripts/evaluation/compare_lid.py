"""Compare language-ID backends on held-out Somali and non-Somali text.

Evaluation items (none used to build any backend):
  * Somali positives: SIB-200 som_Latn test (single sentences) and
    MasakhaNEWS Somali test (news articles).
  * Negatives: the same SIB-200 test sentences in 10 other languages, chosen to
    include regional neighbours (Swahili, Oromo, Amharic, Tigrinya, Arabic) and
    Latin-script languages (English, Hausa, Yoruba, Afrikaans, Indonesian).
  * Code-switched probe (SYNTHETIC, constructed here): the first half of a
    Somali SIB sentence joined to the second half of its English parallel
    sentence. There is no single correct label; we report how often each tool
    calls it Somali.
  * Maay: no Maay text was accessible, so Maay is NOT evaluated.

Usage: python scripts/evaluation/compare_lid.py [--fasttext-model PATH] [--glotlid-model PATH]
"""
import argparse
import json
import sys
import time
from collections import Counter, defaultdict

import _bootstrap  # noqa: F401
from asal import experiments, lid, paths, readers
from asal.download import load_manifest
from asal.textutil import words

REPORT_DIR = paths.REPORTS / "data_v0.2_nllb"


def build_items(split: str = "test"):
    sample = load_manifest(paths.MANIFESTS / "sample-v0.1.yaml")
    lid_m = load_manifest(paths.MANIFESTS / "lid-eval-v0.1.yaml")
    items = []
    by_id = defaultdict(dict)
    for f in sample["files"]:
        if f["split"] != split:
            continue
        group = "som:sib200-sentence" if f["source_id"] == "sib200-som" else "som:masakhanews-article"
        for r in readers.read(f, paths.RAW):
            items.append({"group": group, "gold": "som", "text": r["text"]})
            if f["source_id"] == "sib200-som":
                by_id[r["source_record_id"]]["som"] = r["text"]
    for f in lid_m["files"]:
        if f["split"] != split:
            continue
        code = f["language"].split("_")[0]
        for r in readers.read(f, paths.RAW):
            items.append({"group": f"neg:{f['language']}", "gold": code, "text": r["text"]})
            if code == "eng":
                by_id[r["source_record_id"]]["eng"] = r["text"]
    if split != "test":
        return items
    for rid, pair in sorted(by_id.items()):
        if "som" in pair and "eng" in pair:
            so, en = words(pair["som"]), pair["eng"].split()
            text = " ".join(pair["som"].split()[: max(1, len(so) // 2)] + en[len(en) // 2:])
            items.append({"group": "cs:som-eng-synthetic", "gold": "mixed", "text": text})
    return items


def evaluate(backend, items):
    t0 = time.perf_counter()
    preds = [backend.predict(it["text"]) for it in items]
    elapsed = time.perf_counter() - t0
    tp = sum(1 for it, p in zip(items, preds) if it["gold"] == "som" and p.label == "som")
    fn = sum(1 for it, p in zip(items, preds) if it["gold"] == "som" and p.label != "som")
    fp = sum(1 for it, p in zip(items, preds) if it["gold"] not in ("som", "mixed") and p.label == "som")
    prec = tp / (tp + fp) if tp + fp else 0.0
    rec = tp / (tp + fn) if tp + fn else 0.0
    groups = defaultdict(Counter)
    for it, p in zip(items, preds):
        groups[it["group"]]["n"] += 1
        groups[it["group"]]["called_somali"] += p.label == "som"
        groups[it["group"]][f"label:{p.label}"] += 1
    per_group = {}
    for g, c in sorted(groups.items()):
        top = sorted(((k[6:], v) for k, v in c.items() if k.startswith("label:")), key=lambda kv: -kv[1])[:3]
        per_group[g] = {"n": c["n"], "called_somali": c["called_somali"],
                        "called_somali_rate": round(c["called_somali"] / c["n"], 4), "top_labels": top}
    return {
        "backend": backend.name,
        "somali_precision": round(prec, 4),
        "somali_recall": round(rec, 4),
        "somali_f1": round(2 * prec * rec / (prec + rec), 4) if prec + rec else 0.0,
        "true_positives": tp, "false_negatives": fn, "false_positives": fp,
        "seconds": round(elapsed, 2),
        "per_group": per_group,
    }


def markdown(results, items, exp_id):
    counts = Counter(it["group"] for it in items)
    lines = [f"# LID comparison ({exp_id})", "",
             "Generated by `scripts/evaluation/compare_lid.py`. Somali = positive class.", "",
             "| backend | precision | recall | F1 | FP | FN | seconds |", "|---|---|---|---|---|---|---|"]
    for r in results:
        lines.append(f"| {r['backend']} | {r['somali_precision']} | {r['somali_recall']} | {r['somali_f1']} | "
                     f"{r['false_positives']} | {r['false_negatives']} | {r['seconds']} |")
    lines += ["", "## Share of items labelled Somali, by group", "",
              "| group | n | " + " | ".join(r["backend"] for r in results) + " |",
              "|---|---|" + "---|" * len(results)]
    for g in sorted(counts):
        lines.append(f"| {g} | {counts[g]} | " + " | ".join(
            str(r["per_group"][g]["called_somali_rate"]) for r in results) + " |")
    lines += ["", "`cs:som-eng-synthetic` is a constructed probe with no single correct label.",
              "Maay was not evaluated: no Maay text was available.", ""]
    return "\n".join(lines)


def tune_ensemble(heuristic, lingua_backend) -> tuple[float, list]:
    """Pick the ensemble's low threshold by Somali F1 on the dev splits (never on test)."""
    dev = build_items("dev")
    h_scores = [heuristic.score(it["text"]) for it in dev]
    l_labels = [lingua_backend.predict(it["text"]).label for it in dev]
    curve = []
    for t in [round(0.05 * i, 2) for i in range(0, 11)]:
        pred = [h >= heuristic.threshold or (lab == "som" and h >= t) for h, lab in zip(h_scores, l_labels)]
        tp = sum(p and it["gold"] == "som" for p, it in zip(pred, dev))
        fp = sum(p and it["gold"] != "som" for p, it in zip(pred, dev))
        fn = sum((not p) and it["gold"] == "som" for p, it in zip(pred, dev))
        prec = tp / (tp + fp) if tp + fp else 0.0
        rec = tp / (tp + fn) if tp + fn else 0.0
        f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
        curve.append({"low_threshold": t, "precision": round(prec, 4), "recall": round(rec, 4), "f1": round(f1, 4)})
    best = max(curve, key=lambda c: (c["f1"], c["low_threshold"]))
    return best["low_threshold"], curve


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fasttext-model")
    ap.add_argument("--glotlid-model")
    args = ap.parse_args()
    items = build_items()
    backends = lid.available_backends(args.fasttext_model, args.glotlid_model)
    tuning = None
    lingua_b = next((b for b in backends if b.name == "lingua"), None)
    if lingua_b is not None:
        heur = next(b for b in backends if b.name == "asal-heuristic")
        t, curve = tune_ensemble(heur, lingua_b)
        tuning = {"tuned_on": "SIB-200 dev (11 languages) + MasakhaNEWS Somali dev", "selected_low_threshold": t,
                  "curve": curve}
        backends.append(lid.EnsembleLID(heur, lingua_b, low_threshold=t))
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    exp_id, _ = experiments.register("LID", "lid-comparison", config={"backends": [b.name for b in backends],
                                     "ensemble_tuning": {k: v for k, v in (tuning or {}).items() if k != "curve"},
                                     "items": dict(Counter(it["group"] for it in items))},
                                     description="Somali LID comparison on held-out SIB-200 / MasakhaNEWS test data.",
                                     dataset="sample-v0.1 + lid-eval-v0.1", track="not_applicable")
    results = [evaluate(b, items) for b in backends]
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    (REPORT_DIR / "lid_comparison.json").write_text(json.dumps({"experiment_id": exp_id, "ensemble_tuning": tuning,
                                                                "results": results},
                                                               indent=2, ensure_ascii=False), encoding="utf-8")
    md = markdown(results, items, exp_id)
    if tuning:
        md += (f"\nasal-ensemble low threshold {tuning['selected_low_threshold']} was selected by F1 on dev splits "
               "only; the numbers above are on test splits.\n")
    (REPORT_DIR / "lid_comparison.md").write_text(md, encoding="utf-8")
    experiments.update(exp_id, status="completed",
                       results={r["backend"]: {"f1": r["somali_f1"], "precision": r["somali_precision"],
                                               "recall": r["somali_recall"]} for r in results})
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
